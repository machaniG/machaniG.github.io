#!/usr/bin/env python3
"""
build.py - turns content/projects/*.md + images/<project-id>/* into projects.js

Run it after every edit:   python3 build.py
Then open index.html (or push to GitHub). No libraries needed.
"""
import json, re, html
from pathlib import Path

ROOT = Path(__file__).parent
IMG_EXT = {".png", ".jpg", ".jpeg", ".webp", ".gif", ".svg", ".avif"}

def inline(t):
    t = html.escape(t, quote=False)
    t = re.sub(r"!\[([^\]]*)\]\(([^)]+)\)", r'<img src="\2" alt="\1" loading="lazy">', t)
    t = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2" target="_blank" rel="noopener">\1</a>', t)
    t = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", t)
    t = re.sub(r"(?<!\*)\*([^*]+)\*(?!\*)", r"<i>\1</i>", t)
    t = re.sub(r"`([^`]+)`", r"<code>\1</code>", t)
    return t

def md_to_html(block):
    """Tiny markdown: paragraphs, - bullets, **bold**, *italic*, `code`, [links](url), ![img](path)"""
    out, para, items = [], [], []
    def flush():
        nonlocal para, items
        if para: out.append("<p>" + inline(" ".join(para)) + "</p>"); para = []
        if items: out.append("<ul>" + "".join(f"<li>{inline(i)}</li>" for i in items) + "</ul>"); items = []
    for line in block.splitlines():
        s = line.strip()
        if not s: flush()
        elif s.startswith(("- ", "* ")):
            if para: flush()
            items.append(s[2:])
        else:
            if items: flush()
            para.append(s)
    flush()
    return "".join(out)

def plain(block):
    return re.sub(r"\s+", " ", re.sub(r"[*`]|!?\[([^\]]*)\]\([^)]*\)", r"\1", block)).strip()

def parse(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", text, re.S)
    if not m: raise SystemExit(f"{path.name}: missing the --- header block at the top")
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.lstrip().startswith("#"):
            k, v = line.split(":", 1); meta[k.strip()] = v.strip()
    secs, cur = [], None
    for line in m.group(2).splitlines():
        if line.startswith("## "): cur = [line[3:].strip(), []]; secs.append(cur)
        elif cur is not None: cur[1].append(line)
    return meta, [(h, "\n".join(b).strip()) for h, b in secs]

projects = []
for f in sorted((ROOT / "content" / "projects").glob("*.md")):
    meta, secs = parse(f)
    pid = f.stem
    p = {"id": pid, "title": meta.get("title", pid), "order": int(meta.get("order", 999))}
    for k in ("who", "metric", "cat", "svc", "time", "role", "repo", "demo", "direct", "status", "kind"):
        if meta.get(k): p[k] = meta[k]
    p["featured"] = meta.get("featured", "").lower() == "true"
    p["seed"] = int(meta.get("seed", 7))
    p["kind"] = p.get("kind", "scatter")
    p["stack"] = [s.strip() for s in meta.get("stack", "").split(",") if s.strip()]
    # plain-text versions used on the cards
    lookup = {h.lower(): b for h, b in secs}
    def find(*names):
        for n in names:
            for h, b in lookup.items():
                if n in h: return b
        return ""
    p["problem"], p["approach"], p["result"] = (plain(find("problem")), plain(find("did", "approach")), plain(find("result")))
    # full sections for the project page
    p["sections"] = [{"h": h, "html": md_to_html(b)} for h, b in secs if b]
    # images: auto-detect from images/<id>/  (cover.* = card image, the rest = screenshots)
    folder = ROOT / "images" / pid
    imgs = sorted(x for x in folder.glob("*") if x.suffix.lower() in IMG_EXT) if folder.exists() else []
    cover = next((x for x in imgs if x.stem.lower() == "cover"), None)
    if meta.get("cover"): p["cover"] = meta["cover"]
    elif cover: p["cover"] = f"images/{pid}/{cover.name}"
    shots = [f"images/{pid}/{x.name}" for x in imgs if x != cover]
    if shots: p["shots"] = shots
    projects.append(p)

projects.sort(key=lambda p: (p["order"], p["id"]))
(ROOT / "projects.js").write_text(
    "/* AUTO-GENERATED by build.py. Do not edit. Edit content/projects/*.md instead. */\n"
    "const PROJECTS=" + json.dumps(projects, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print(f"Built projects.js with {len(projects)} projects: " + ", ".join(p["id"] for p in projects))
